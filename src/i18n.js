function supportedLanguage(locale) {
  if (typeof locale !== 'string') return null;
  const language = locale.trim().toLowerCase().split(/[-_]/)[0];
  return Object.hasOwn(messages, language) ? language : null;
}

// An explicit choice wins over Meta; browser preferences are used outside Meta.
export function selectLanguage({ preference, metaLocale, browserLanguages = [] } = {}) {
  if (preference === 'ja' || preference === 'en') return preference;
  if (typeof metaLocale === 'string' && metaLocale.trim()) return supportedLanguage(metaLocale) || 'en';
  for (const locale of browserLanguages) {
    const language = supportedLanguage(locale);
    if (language) return language;
  }
  return 'en';
}

export function createTranslator(language) {
  const catalog = messages[supportedLanguage(language) || 'en'];
  return (key, values = {}) => {
    if (!Object.hasOwn(catalog, key)) throw new Error('Unknown translation key: ' + key);
    return catalog[key].replace(/\{(\w+)\}/g, (_, name) => {
      if (!Object.hasOwn(values, name)) throw new Error('Missing translation value: ' + name);
      return String(values[name]);
    });
  };
}

// Translate text nodes independently, leaving icons and layout markup intact.
export function translateDocument(root, language) {
  const t = createTranslator(language);
  for (const [attribute, target] of [['data-i18n', null], ['data-i18n-aria-label', 'aria-label'], ['data-i18n-content', 'content']]) {
    for (const node of root.querySelectorAll('[' + attribute + ']')) {
      const text = t(node.getAttribute(attribute));
      if (target) node.setAttribute(target, text);
      else node.textContent = text;
    }
  }
  root.documentElement.lang = language;
  root.title = t('page.title');
}
